/**
 * Mission model (Free Roam Prompt 11). Data only: the rules live in
 * missions.ts, the authored story chain in missionData.ts and the seeded
 * station contracts in contracts.ts.
 *
 * A mission has a stable id, a type, a description, prerequisites, one or
 * more objectives (each with a target rule that is resolved to a concrete
 * system / POI when the mission is accepted), failure conditions and
 * rewards. Its runtime state (accepted, progress, completed, claimed,
 * failed) lives in MissionState and is saved with the profile.
 */
import type { EncounterKind, LootEntry, PoiKind } from '../sector/model.ts';

export const MISSION_TYPES = [
  'discover-system',
  'investigate-anomaly',
  'recover-salvage',
  'destroy-patrol',
  'clear-outpost',
  'deliver-resources',
  'investigate-derelict',
  'locate-rare',
  'survey-region',
  'defend-wreck',
] as const;
export type MissionType = (typeof MISSION_TYPES)[number];

export const MISSION_TYPE_LABEL: Readonly<Record<MissionType, string>> = Object.freeze({
  'discover-system': 'Discover a system',
  'investigate-anomaly': 'Investigate an anomaly',
  'recover-salvage': 'Recover salvage',
  'destroy-patrol': 'Destroy a hostile patrol',
  'clear-outpost': 'Clear an outpost',
  'deliver-resources': 'Deliver resources',
  'investigate-derelict': 'Investigate a derelict',
  'locate-rare': 'Locate a rare component',
  'survey-region': 'Survey a region',
  'defend-wreck': 'Defend a wreck',
});

export const OBJECTIVE_KINDS = ['visit', 'reach-galaxy', 'chart', 'poi', 'destroy', 'clear', 'acquire', 'deliver'] as const;
export type ObjectiveKind = (typeof OBJECTIVE_KINDS)[number];

/**
 * Where an objective happens.
 *  - a system id ('milky-way/sol'): that system;
 *  - 'nearest': resolved on acceptance to the nearest enterable system that
 *    still has what the objective needs (a POI not yet done, a patrol route,
 *    an uncharted or unvisited system, a station for deliveries);
 *  - 'any': anywhere inside the mission's galaxy (or anywhere at all when the
 *    mission has no galaxy).
 */
export type TargetRule = 'nearest' | 'any' | string;

export interface ObjectiveDef {
  readonly kind: ObjectiveKind;
  /** Short imperative line ("Inspect the derelict"); the resolved target name is appended by the UI. */
  readonly label: string;
  /** Units to reach (POIs, kills, systems, resource units). */
  readonly count: number;
  readonly target: TargetRule;
  /** poi objectives. */
  readonly poiKind?: PoiKind | undefined;
  /** clear objectives. */
  readonly encounter?: EncounterKind | undefined;
  /** destroy objectives: only ships flying a patrol route count. */
  readonly patrol?: boolean | undefined;
  /** acquire (any of these) and deliver (the first). */
  readonly resources?: readonly string[] | undefined;
  /** reach-galaxy objectives. */
  readonly galaxy?: string | undefined;
}

export type Prerequisite =
  | { readonly kind: 'mission'; readonly id: string }
  | { readonly kind: 'galaxy'; readonly id: string }
  | { readonly kind: 'charted'; readonly count: number };

export interface FailureRules {
  /** Lane hops allowed after acceptance (counted in jumps, never in real time). */
  readonly deadlineJumps?: number | undefined;
  /** A defence objective fails when its encounter is lost. */
  readonly failOnEncounterLoss?: boolean | undefined;
}

export interface MissionReward {
  readonly marks: number;
  readonly resources: readonly LootEntry[];
  /** Module ids put into station storage. */
  readonly modules: readonly string[];
  /** Navigation data: charts this many unlocked, uncharted systems of the mission's galaxy. */
  readonly charts: number;
  /** Upgrade licences (ships/upgrades.ts UPGRADE_LICENCES). */
  readonly licences: readonly string[];
}

export interface MissionDef {
  readonly id: string;
  readonly type: MissionType;
  readonly source: 'story' | 'contract';
  readonly title: string;
  readonly description: string;
  /** Galaxy the targets are resolved in ('' = wherever the pilot is when accepting). */
  readonly galaxy: string;
  readonly prerequisites: readonly Prerequisite[];
  readonly objectives: readonly ObjectiveDef[];
  readonly failure: FailureRules;
  readonly rewards: MissionReward;
}

/** Target already satisfied when the mission was accepted (nothing left to find): counts as done. */
export const TARGET_DONE = '-';

/** A contract offer as generated by a station board (saved with the accepted contract). */
export interface ContractSpec {
  readonly type: MissionType;
  /** Station system that posted it. */
  readonly station: string;
  /** Resolved target: system id or `system#localId`. */
  readonly target: string;
  readonly count: number;
  /** acquire / deliver resource ('' = none). */
  readonly resource: string;
  readonly marks: number;
  /** Lane hops allowed (0 = no deadline). */
  readonly deadline: number;
  /** Target system difficulty 1..5 (reward and rare-roll context). */
  readonly difficulty: number;
}

export interface ActiveMission {
  readonly id: string;
  /** Jump counter when accepted (deadlines). */
  readonly at: number;
  /** Progress per objective. */
  readonly progress: readonly number[];
  /** Resolved target per objective (system id, `system#localId`, '' = anywhere, TARGET_DONE). */
  readonly targets: readonly string[];
  readonly contract?: ContractSpec | undefined;
}

export interface MissionState {
  /** Lane hops flown since Prompt 11 (deadline clock). */
  readonly jumps: number;
  readonly active: readonly ActiveMission[];
  /** Objectives met (in completion order). Completed but not claimed = ready to turn in. */
  readonly completed: readonly string[];
  /** Rewards paid. A subset of completed; a mission id is paid at most once. */
  readonly claimed: readonly string[];
  readonly failed: readonly string[];
  /** Contract specs of completed missions waiting to be turned in (their defs are rebuilt from these). */
  readonly ready: Readonly<Record<string, ContractSpec>>;
}

export const EMPTY_MISSIONS: MissionState = Object.freeze({ jumps: 0, active: Object.freeze([]), completed: Object.freeze([]), claimed: Object.freeze([]), failed: Object.freeze([]), ready: Object.freeze({}) });

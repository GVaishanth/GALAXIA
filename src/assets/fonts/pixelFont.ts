const FALLBACK = G['?']!;

export function glyph(ch: string): readonly string[] {
  return G[ch.toUpperCase()] ?? FALLBACK;
}

export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * GLYPH_ADVANCE - 1;
}

